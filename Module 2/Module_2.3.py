print(2 ** 3) # Exponent
print(2 * 3) # Product
print(6 / 3) # Division
print(6 // 3) # Floor division
print(14 % 4) # Module (The excedent of a division operation)
# 14/2 = 3 and 3 * 4 = 12 so 14-12 = 2 (Module of the operation)

print(2 - 3) # Difference


# The operations in python are readed from left to right
print(9 % 6 % 2) # R = 1

# The exponential operations are readed form right to left
print(2 ** 2 ** 3)
print(-3 ** 2)